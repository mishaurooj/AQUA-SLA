r"""AQUA-SLA Script 47B: assignment-preserving warm-start QAOA and classical neighborhood controls.

This is a NEW experiment, not a proof of quantum speedup. It imports the
Script 46 QAOA problem generator so cost and capacity constraints stay fixed.
It benchmarks eight warm-start settings plus two uniform XY controls against
MILP and equally informed classical neighborhood search.

Install beside 46_qaoa_independent_ablation.py in the Code folder.

python 47_qaoa_warmstart_ablation.py --data ..\Dataset\processed\aqua_sla_prepared.csv --out ..\results\47_warmstart
python 47_qaoa_warmstart_ablation.py --data processed.zip --out results47 --blocks 5

No claim of measured contractual SLA or hardware speedup is made: SLO outcomes
are generated by a scheduling model, and circuits run on a CPU statevector.
"""
from __future__ import annotations
import argparse, importlib.util, json, time
from pathlib import Path
import numpy as np
import pandas as pd
from scipy.optimize import minimize, milp, Bounds, LinearConstraint


def original_module():
    path = Path(__file__).resolve().with_name('46_qaoa_independent_ablation.py')
    if not path.exists():
        raise FileNotFoundError('Copy 46_qaoa_independent_ablation.py beside this script')
    spec=importlib.util.spec_from_file_location('qaoa46',path)
    mod=importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def amplitude_distribution(energies, n, depth, angles, initial_assignment=None, strength=.85):
    """Statevector unitary QAOA in n logical qubits (2n one-hot physical bits).

    Each logical |0/1> is the physical one-hot |10/01>. RX logical mixer
    corresponds to a one-hot-preserving excitation-swap rotation. The warm
    start prepares a valid one-hot superposition using Ry basis rotations.
    """
    idx=np.arange(1<<n)
    if initial_assignment is None:
        state=np.full(len(idx),1/np.sqrt(len(idx)),dtype=complex)
    else:
        a=np.asarray(initial_assignment,dtype=int)
        p1=np.where(a==1,strength,1-strength)
        bits=((idx[:,None]>>np.arange(n)[None,:])&1).astype(bool)
        state=np.sqrt(np.prod(np.where(bits,p1,1-p1),axis=1)).astype(complex)
    e=(energies-energies.min())/max(float(np.ptp(energies)),1e-9)
    for d in range(depth):
        state *= np.exp(-1j*angles[d]*e)
        beta=angles[d+depth]
        for j in range(n):
            b=state.reshape(-1,2**(j+1));j0=np.arange(2**j);j1=j0+(1<<j)
            x=b[:,j0].copy();y=b[:,j1].copy()
            b[:,j0]=np.cos(beta)*x-1j*np.sin(beta)*y
            b[:,j1]=np.cos(beta)*y-1j*np.sin(beta)*x
    probs=np.abs(state)**2
    return probs/probs.sum()


def optimize(energies, n, depth, start, strength, maxfev, seed):
    rng=np.random.default_rng(seed)
    init=np.r_[rng.uniform(.4,2,depth),rng.uniform(.2,1.1,depth)]
    e=(energies-energies.min())/max(float(np.ptp(energies)),1e-9)
    cnt=[0]
    tic=time.perf_counter()
    def fun(theta):
        cnt[0]+=1
        return float(amplitude_distribution(energies,n,depth,theta,start,strength)@e)
    m=minimize(fun,init,method='Nelder-Mead',options={'maxfev':maxfev,'xatol':.06,'fatol':.0001})
    prob=amplitude_distribution(energies,n,depth,m.x,start,strength)
    return prob,time.perf_counter()-tic,cnt[0]


def best_neighborhood(p, mod, center, rng, draws):
    """Classical comparator has the SAME greedy initialization as warm QAOA."""
    n=len(center)
    # Predeclared mixture of Hamming radii 1, 2, and roughly 1/3 of bits.
    radius=rng.choice([1,2,max(3,n//3)],size=draws)
    choices=np.tile(center,(draws,1))
    for k in range(draws):
        mask=rng.choice(n,size=min(n,int(radius[k])),replace=False)
        choices[k,mask] ^= 1
    choices=np.unique(choices,axis=0)
    good=None
    for x in choices:
        v=mod.assess(p,x)
        if v['feasible'] and (good is None or v['objective']<good[0]):good=(v['objective'],x)
    return None if good is None else good[1]


def repair_feasible_seed(p):
    """Capacity-only MILP repair; minimizes Hamming distance to unconstrained
    per-task cheapest-host choices. Does NOT minimize the scheduling objective.
    The cost of this classical repair is charged to the quantum warm start.
    """
    n=p['n'];m=2
    prefs=np.argmin(p['cost'],axis=1)
    c=np.array([0. if r==prefs[t] else 1. for t in range(n) for r in range(m)])
    rows=[];low=[];high=[]
    for t in range(n):
        v=np.zeros(n*m);v[t*m:(t+1)*m]=1.
        rows.append(v);low.append(1.);high.append(1.)
    for r in range(m):
        for field,cap in [('cpu','cpu_caps'),('mem','mem_caps')]:
            v=np.zeros(n*m);v[r::m]=p[field]
            rows.append(v);low.append(0.);high.append(p[cap][r])
    tic=time.perf_counter()
    res=milp(c=c,integrality=np.ones(n*m),bounds=Bounds(0,1),
             constraints=LinearConstraint(np.asarray(rows),np.asarray(low),np.asarray(high)),
             options={'time_limit':20.})
    seconds=time.perf_counter()-tic
    if res.x is None:raise RuntimeError('Feasibility repair MILP failed')
    x=np.argmax(res.x.reshape(n,m),axis=1)
    if not np.isclose(np.sum(x>=0),n) or not p['n']==len(x):raise AssertionError('Invalid seed')
    return x.astype(int),seconds


def run(args):
    out=Path(args.out);out.mkdir(parents=True,exist_ok=True)
    mod=original_module()
    tasks=mod.read_tasks(args.data)
    data=[]
    configs=[(s,p,sh) for s in (.65,.85) for p in (1,2) for sh in (512,1024)]
    for n in args.sizes:
        if n>16:raise ValueError('Exact CPU simulation and brute force limited to 16 tasks')
        for block,chunk in mod.choose_blocks(tasks,n,args.blocks,args.seed+n+47):
            p=mod.make_instance(chunk,args.seed+n*71+block)
            optimum,_=mod.enumerate_optimum(p)
            milp_x,milp_s,status=mod.milp_optimum(p)
            if abs(mod.assess(p,milp_x)['objective']-optimum)>1e-6:raise AssertionError('MILP optimum inconsistency')
            e=mod.feasible_diagonal(p)
            tic=time.perf_counter();center=mod.greedy(p);center_sec=time.perf_counter()-tic
            seed_origin='greedy'
            if center is None:
                center,repair_sec=repair_feasible_seed(p)
                center_sec+=repair_sec
                seed_origin='capacity_feasibility_MILP_repair'
            def record(name,x,runtime,evals,shots,base):
                info=mod.assess(p,x) if x is not None else None
                row=dict(tasks=n,block=block,method=name,initializer=base,
                    objective=info['objective'] if info else np.nan,
                    optimal_recovery=int(info is not None and info['feasible'] and abs(info['objective']-optimum)<1e-6),
                    feasible=int(info is not None and info['feasible']),
                    objective_gap_pct=(100*(info['objective']/optimum-1) if info and info['feasible'] else np.nan),
                    slo_miss_rate=info['slo_miss_rate'] if info else np.nan,
                    makespan=info['makespan'] if info else np.nan,
                    cpu_utilization=info['cpu_utilization'] if info else np.nan,
                    memory_utilization=info['memory_utilization'] if info else np.nan,
                    energy=info['total_energy'] if info else np.nan,
                    runtime_seconds=runtime,expectation_evaluations=evals,shots=shots)
                data.append(row)
            record('MILP',milp_x,milp_s,0,0,'none')
            record('Feasible_start',center,center_sec,0,0,seed_origin)
            tic=time.perf_counter();loc=mod.local_search(p,center)
            record('Greedy+local_search',loc,center_sec+time.perf_counter()-tic,0,0,seed_origin)
            for draws in [512,2048,max(2048,args.maxfev*512)]:
                rng=np.random.default_rng(args.seed+n*1000+block*27+draws)
                tic=time.perf_counter();x=best_neighborhood(p,mod,center,rng,draws)
                name='Greedy_neighborhood_budget' if draws>2048 else f'Greedy_neighborhood_{draws}'
                record(name,x,center_sec+time.perf_counter()-tic,draws,draws,seed_origin)
            # Required unrestricted classical controls: the greedy neighborhood
            # alone is too narrow, because a good solution may differ in >3 bits.
            # Optimizer-budget control is deliberately conservative for QAOA.
            for draws in [512,2048,max(2048,args.maxfev*512)]:
                rg=np.random.default_rng(args.seed+n*1777+block*51+draws)
                tic=time.perf_counter()
                x=mod.best_of_random(p,rg,draws,uniform_bits=False)
                name='Uniform_random_budget' if draws>2048 else f'Uniform_random_{draws}'
                record(name,x,time.perf_counter()-tic,draws,draws,'uniform')
            for depth in (1,2):
                prob,dt,ev=optimize(e,n,depth,None,.5,args.maxfev,args.seed+n*88+block*11+depth)
                ids=np.random.default_rng(args.seed+n*400+block*25+depth).choice(len(prob),size=1024,p=prob)
                record(f'UniformXY_p{depth}_1024',mod.recover(p,ids,'XY'),dt,ev,1024,'uniform')
            for strength,depth,shots in configs:
                key=round(strength*100)
                prob,dt,ev=optimize(e,n,depth,center,strength,args.maxfev,
                    args.seed+n*111+block*31+depth*5+key)
                ids=np.random.default_rng(args.seed+n*123+block*37+key*5+depth*3+shots).choice(len(prob),size=shots,p=prob)
                record(f'WarmXY_s{key}_p{depth}_shots{shots}',mod.recover(p,ids,'XY'),dt+center_sec,ev,shots,seed_origin)
            print(f'tasks={n}, instance={block}, optimal={optimum:.5f}',flush=True)
    df=pd.DataFrame(data)
    df.to_csv(out/'47_qaoa_instances.csv',index=False)
    summary=df.groupby(['tasks','method'],as_index=False).agg(
        instances=('block','count'),optimal_recovery=('optimal_recovery','mean'),
        feasible_rate=('feasible','mean'),mean_gap_pct=('objective_gap_pct','mean'),
        mean_slo_miss=('slo_miss_rate','mean'),mean_makespan=('makespan','mean'),
        mean_cpu_util=('cpu_utilization','mean'),mean_mem_util=('memory_utilization','mean'),
        mean_energy=('energy','mean'),mean_runtime_s=('runtime_seconds','mean'),
        mean_expectation_evals=('expectation_evaluations','mean'))
    summary.to_csv(out/'47_qaoa_summary.csv',index=False)
    controls=['MILP','Greedy+local_search','Greedy_neighborhood_512','Greedy_neighborhood_2048','Greedy_neighborhood_budget','Uniform_random_512','Uniform_random_2048','Uniform_random_budget']
    comparisons=[]
    for n in args.sizes:
        subset=df[df.tasks==n]
        for qmethod in sorted(m for m in subset.method.unique() if m.startswith('WarmXY_')):
            a=subset[subset.method==qmethod].set_index('block')
            for bname in controls:
                b=subset[subset.method==bname].set_index('block')
                ix=a.index.intersection(b.index)
                if len(ix)==0:continue
                comparisons.append(dict(tasks=n,qaoa=qmethod,baseline=bname,
                     paired_instances=len(ix),
                     delta_optimal_recovery=float((a.loc[ix,'optimal_recovery']-b.loc[ix,'optimal_recovery']).mean()),
                     qaoa_runtime_over_baseline=float(a.loc[ix,'runtime_seconds'].mean()/max(b.loc[ix,'runtime_seconds'].mean(),1e-12))))
    pc=pd.DataFrame(comparisons);pc.to_csv(out/'47_qaoa_paired.csv',index=False)
    report=dict(eight_warmstart_variants=[f'WarmXY_s{int(s*100)}_p{depth}_shots{shots}' for s,depth,shots in configs],
       simulator='exact numpy statevector CPU',
       original_cost_definition='46_qaoa_independent_ablation.py capacity-constrained two-host generated cases',
       concrete_objectives='objective, optimality gap, optimal recovery, feasibility, modeled SLO misses, makespan, utilization, energy, runtime',
       quantum_computational_advantage_proven=False,
       note='MILP exact optimum is mathematically unbeatable in objective value; randomized samples must be compared to equally-informed greedy-centered controls.',
       results_by_size={str(n):dict(
          best_warm_xy_recovery=float(summary[(summary.tasks==n)&summary.method.str.startswith('WarmXY')].optimal_recovery.max()),
          best_classical_recovery=float(summary[(summary.tasks==n)&summary.method.isin(controls)].optimal_recovery.max())) for n in args.sizes})
    (out/'47_qaoa_verdict.json').write_text(json.dumps(report,indent=2))
    print(json.dumps(report,indent=2))

