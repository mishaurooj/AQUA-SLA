def main() -> int:
    args = parse_args()
    project_dir = args.project_dir.resolve()
    code_dir = project_dir / "Code"
    results_root = project_dir / "results"
    runs_root = results_root / "aqua_sla_experiment_runs"
    run_dir = runs_root / create_run_id(args.run_name)
    layout = ensure_layout(run_dir)

    environment = os.environ.copy()
    environment.setdefault(
        "IQUANTUM_HOME",
        str(project_dir / "third_party" / "iQuantum"),
    )
    environment.setdefault("AQUA_RUN_IQUANTUM", "1")

    execution_records: list[dict[str, Any]] = []
    collection_records: dict[str, Any] = {}

    selected_experiments = EXPERIMENTS
    if args.mode == "iquantum-only":
        selected_experiments = [
            item for item in EXPERIMENTS
            if item["name"] == "iquantum_platform"
        ]
    elif args.mode == "circuits-only":
        selected_experiments = []

    should_run = args.mode in {"full", "iquantum-only", "circuits-only"}

    print("=" * 72)
    print("AQUA-SLA MASTER EXPERIMENT RUN")
    print(f"Mode:       {args.mode}")
    print(f"Project:    {project_dir}")
    print(f"Run output: {run_dir}")
    print("=" * 72)

    if should_run and args.mode != "circuits-only":
        for experiment in selected_experiments:
            script = code_dir / experiment["script"]
            print(f"\nRunning: {script.name}")
            result = run_script(
                args.python,
                script,
                project_dir,
                layout["09_logs"],
                environment,
            )
            result["experiment"] = experiment["name"]
            execution_records.append(result)
            print(
                f"  status={result['status']} "
                f"returncode={result['returncode']} "
                f"elapsed={result['elapsed_seconds']:.1f}s"
            )
            if not result["success"] and not args.continue_on_error:
                print("Stopping because an experiment failed.")
                print("Use --continue-on-error to package remaining outputs.")
                break

    if (
        should_run
        and not args.skip_circuit_generators
        and args.mode in {"full", "circuits-only"}
    ):
        for script_name in CIRCUIT_SCRIPTS:
            script = code_dir / script_name
            print(f"\nGenerating circuit figures: {script.name}")
            result = run_script(
                args.python,
                script,
                project_dir,
                layout["09_logs"],
                environment,
            )
            result["experiment"] = "quantum_circuit_generation"
            execution_records.append(result)
            print(
                f"  status={result['status']} "
                f"returncode={result['returncode']}"
            )
            if not result["success"] and not args.continue_on_error:
                print("Circuit generator failed; collection will still continue.")
                break

    # Always collect the available outputs, even after a failed child script.
    for experiment in selected_experiments:
        destination = layout[experiment["destination"]]
        collection_records[experiment["name"]] = collect_experiment_output(
            project_dir,
            experiment["output_candidates"],
            destination,
        )

    print("\nCollecting all quantum-circuit artifacts...")
    collection_records["quantum_circuits"] = collect_quantum_circuits(
        project_dir,
        layout["06_quantum_circuits"],
    )

    print("Collecting architecture figures...")
    collection_records["architecture"] = collect_architecture(
        project_dir,
        layout["07_architecture"],
    )

    print("Snapshotting source code...")
    collection_records["source_snapshot"] = {
        "files_copied": snapshot_sources(
            project_dir,
            code_dir,
            layout["10_source_snapshot"],
        )
    }

    print("Building consolidated result inventory and workbook...")
    collection_records["consolidated_tables"] = consolidate_tables(
        run_dir,
        layout["08_consolidated_tables"],
    )

    write_manifest(
        layout["00_manifest"],
        run_dir,
        project_dir,
        args,
        execution_records,
        collection_records,
    )

    success_count = sum(bool(item.get("success")) for item in execution_records)
    failure_count = len(execution_records) - success_count

    print("\n" + "=" * 72)
    print("PACKAGING COMPLETED")
    print(f"Run directory:       {run_dir}")
    print(f"Successful scripts:  {success_count}")
    print(f"Failed scripts:      {failure_count}")
    print(
        "Circuit artifacts:  "
        f"{collection_records['quantum_circuits']['total_unique_circuit_artifacts']}"
    )
    workbook_info = collection_records["consolidated_tables"]
    if workbook_info.get("workbook_created"):
        print(f"Combined workbook:   {workbook_info['workbook']}")
    else:
        print("Combined workbook:   skipped")
        print(f"Reason:              {workbook_info.get('workbook_error')}")
        print(f"CSV inventory:       {workbook_info.get('inventory_csv')}")
    print("=" * 72)

    # Return non-zero only when scripts were requested and all requested scripts failed.
    if execution_records and success_count == 0:
        return 1
    return 0


