def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def copy_file_unique(source: Path, destination_dir: Path) -> Path:
    destination_dir.mkdir(parents=True, exist_ok=True)
    destination = destination_dir / source.name
    if destination.exists():
        try:
            if sha256_file(source) == sha256_file(destination):
                return destination
        except OSError:
            pass
        stem, suffix = source.stem, source.suffix
        index = 2
        while destination.exists():
            destination = destination_dir / f"{stem}_{index}{suffix}"
            index += 1
    shutil.copy2(source, destination)
    return destination


def copy_tree_merge(source: Path, destination: Path) -> int:
    if not source.exists():
        return 0
    count = 0
    for item in source.rglob("*"):
        if not item.is_file():
            continue
        relative = item.relative_to(source)
        target = destination / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(item, target)
        count += 1
    return count


def run_script(
    python_executable: str,
    script_path: Path,
    project_dir: Path,
    log_dir: Path,
    environment: dict[str, str],
) -> dict[str, Any]:
    started = time.perf_counter()
    log_dir.mkdir(parents=True, exist_ok=True)
    stdout_path = log_dir / f"{script_path.stem}_stdout.txt"
    stderr_path = log_dir / f"{script_path.stem}_stderr.txt"

    if not script_path.exists():
        return {
            "script": str(script_path),
            "success": False,
            "returncode": None,
            "elapsed_seconds": 0.0,
            "status": "script_not_found",
            "stdout": str(stdout_path),
            "stderr": str(stderr_path),
        }

    command = [python_executable, str(script_path)]
    try:
        completed = subprocess.run(
            command,
            cwd=script_path.parent,
            env=environment,
            capture_output=True,
            text=True,
            check=False,
        )
        stdout_path.write_text(completed.stdout, encoding="utf-8", errors="replace")
        stderr_path.write_text(completed.stderr, encoding="utf-8", errors="replace")
        return {
            "script": str(script_path),
            "command": command,
            "success": completed.returncode == 0,
            "returncode": completed.returncode,
            "elapsed_seconds": time.perf_counter() - started,
            "status": "completed" if completed.returncode == 0 else "failed",
            "stdout": str(stdout_path),
            "stderr": str(stderr_path),
        }
    except Exception as exc:
        stderr_path.write_text(
            traceback.format_exc(),
            encoding="utf-8",
            errors="replace",
        )
        return {
            "script": str(script_path),
            "command": command,
            "success": False,
            "returncode": None,
            "elapsed_seconds": time.perf_counter() - started,
            "status": f"{type(exc).__name__}: {exc}",
            "stdout": str(stdout_path),
            "stderr": str(stderr_path),
        }


def collect_experiment_output(
    project_dir: Path,
    candidates: Iterable[str],
    destination: Path,
) -> dict[str, Any]:
    copied = 0
    found_sources: list[str] = []
    for relative in candidates:
        source = project_dir / Path(relative)
        if source.exists():
            found_sources.append(str(source))
            copied += copy_tree_merge(source, destination)
    return {
        "found_sources": found_sources,
        "files_copied": copied,
        "destination": str(destination),
    }


def collect_quantum_circuits(project_dir: Path, destination: Path) -> dict[str, Any]:
    """
    Preserve quantum-circuit evidence separately.

    Folder structure:
      qasm/          OpenQASM files
      qpy/           serialized Qiskit circuits
      text_drawings/ text circuit drawings
      images/        PNG/JPEG/SVG/PDF circuit figures
      metadata/      circuit CSV/JSON metadata
      source_folders/full copies of known circuit directories
    """
    subdirs = {
        "qasm": destination / "qasm",
        "qpy": destination / "qpy",
        "text": destination / "text_drawings",
        "images": destination / "images",
        "metadata": destination / "metadata",
        "sources": destination / "source_folders",
    }
    for directory in subdirs.values():
        directory.mkdir(parents=True, exist_ok=True)

    records: list[dict[str, Any]] = []
    seen_hashes: set[str] = set()

    # First copy the complete known circuit directories without flattening.
    for relative in CIRCUIT_SOURCE_CANDIDATES:
        source = project_dir / relative
        if source.exists():
            copy_tree_merge(source, subdirs["sources"] / safe_name(relative))

    # Then build a normalized, deduplicated circuit library.
    roots = [
        project_dir / "results",
        project_dir / "Code",
    ]
    for root in roots:
        if not root.exists():
            continue
        for file in root.rglob("*"):
            if not file.is_file() or file.suffix.lower() not in CIRCUIT_EXTENSIONS:
                continue

            lower_name = file.name.lower()
            lower_path = str(file).lower()
            circuit_related = any(
                token in lower_name or token in lower_path
                for token in [
                    "circuit", "qaoa", "feature_map", "measurement",
                    "state_preparation", "quantum_state", "qasm", "qpy",
                ]
            )
            if not circuit_related:
                continue

            try:
                digest = sha256_file(file)
            except OSError:
                continue
            if digest in seen_hashes:
                continue
            seen_hashes.add(digest)

            suffix = file.suffix.lower()
            if suffix in {".qasm", ".qasm2", ".qasm3"}:
                target_group = "qasm"
            elif suffix == ".qpy":
                target_group = "qpy"
            elif suffix == ".txt":
                target_group = "text"
            elif suffix in {".png", ".jpg", ".jpeg", ".svg", ".pdf"}:
                target_group = "images"
            else:
                target_group = "metadata"

            copied = copy_file_unique(file, subdirs[target_group])
            records.append({
                "source": str(file),
                "saved_as": str(copied),
                "type": target_group,
                "extension": suffix,
                "size_bytes": file.stat().st_size,
                "sha256": digest,
            })

    index_path = destination / "quantum_circuit_inventory.csv"
    pd.DataFrame(records).to_csv(index_path, index=False)

    summary = {
        "total_unique_circuit_artifacts": len(records),
        "qasm_files": sum(r["type"] == "qasm" for r in records),
        "qpy_files": sum(r["type"] == "qpy" for r in records),
        "text_drawings": sum(r["type"] == "text" for r in records),
        "circuit_images": sum(r["type"] == "images" for r in records),
        "metadata_files": sum(r["type"] == "metadata" for r in records),
        "inventory": str(index_path),
    }
    (destination / "quantum_circuit_summary.json").write_text(
        json.dumps(summary, indent=2),
        encoding="utf-8",
    )
    return summary


def collect_architecture(project_dir: Path, destination: Path) -> dict[str, Any]:
    records = []
    seen = set()
    for pattern in ARCHITECTURE_PATTERNS:
        for source in project_dir.rglob(pattern):
            if not source.is_file():
                continue
            try:
                digest = sha256_file(source)
            except OSError:
                continue
            if digest in seen:
                continue
            seen.add(digest)
            copied = copy_file_unique(source, destination)
            records.append({
                "source": str(source),
                "saved_as": str(copied),
                "sha256": digest,
            })

    pd.DataFrame(records).to_csv(
        destination / "architecture_inventory.csv",
        index=False,
    )
    return {"architecture_files": len(records)}


def snapshot_sources(project_dir: Path, code_dir: Path, destination: Path) -> int:
    copied = 0
    if code_dir.exists():
        for file in code_dir.iterdir():
            if file.is_file() and file.suffix.lower() in SOURCE_EXTENSIONS:
                copy_file_unique(file, destination / "python_and_config")
                copied += 1

    iquantum_bridge = (
        project_dir
        / "third_party"
        / "iQuantum"
        / "modules"
        / "iquantum-examples"
        / "src"
        / "main"
        / "java"
        / "org"
        / "iquantum"
        / "examples"
        / "experimental"
        / "AquaSlaIQuantumBridge.java"
    )
    if iquantum_bridge.exists():
        copy_file_unique(iquantum_bridge, destination / "java_bridge")
        copied += 1
    return copied


def consolidate_tables(run_dir: Path, destination: Path) -> dict[str, Any]:
    """
    Copy every table/report into one searchable directory while retaining
    provenance in an inventory. This does not replace the separate folders.
    """
    records = []
    dataframes = []
    excluded = {destination.resolve()}

    for file in run_dir.rglob("*"):
        if not file.is_file() or file.suffix.lower() not in TABLE_EXTENSIONS:
            continue
        if any(parent.resolve() in excluded for parent in file.parents):
            continue
        if "10_source_snapshot" in file.parts or "09_logs" in file.parts:
            continue

        relative = file.relative_to(run_dir)
        group = safe_name(str(relative.parent))
        target_dir = destination / group
        copied = copy_file_unique(file, target_dir)

        row_count = None
        column_count = None
        if file.suffix.lower() == ".csv":
            try:
                frame = pd.read_csv(file)
                row_count = len(frame)
                column_count = len(frame.columns)
                if 0 < len(frame) <= 50000:
                    temp = frame.copy()
                    temp.insert(0, "_source_file", str(relative))
                    dataframes.append(temp)
            except Exception:
                pass

        records.append({
            "source_relative_path": str(relative),
            "consolidated_copy": str(copied.relative_to(run_dir)),
            "extension": file.suffix.lower(),
            "size_bytes": file.stat().st_size,
            "rows": row_count,
            "columns": column_count,
            "sha256": sha256_file(file),
        })

    inventory = pd.DataFrame(records)
    inventory.to_csv(destination / "all_results_inventory.csv", index=False)

    # A single workbook with an inventory and selected compact CSV tables.
    workbook_path = destination / "AQUA_SLA_ALL_RESULTS.xlsx"
    workbook_created = False
    workbook_error = None

    try:
        import openpyxl  # noqa: F401

        with pd.ExcelWriter(workbook_path, engine="openpyxl") as writer:
            inventory.to_excel(writer, sheet_name="Inventory", index=False)
            sheet_counter = 1
            for record in records:
                if record["extension"] != ".csv":
                    continue
                source = run_dir / record["source_relative_path"]
                try:
                    frame = pd.read_csv(source)
                except Exception:
                    continue
                if len(frame) > 200000 or len(frame.columns) > 100:
                    continue
                sheet_name = safe_name(source.stem)[:24]
                sheet_name = f"{sheet_counter:02d}_{sheet_name}"[:31]
                frame.to_excel(writer, sheet_name=sheet_name, index=False)
                sheet_counter += 1
                if sheet_counter > 80:
                    break

        workbook_created = True

    except ModuleNotFoundError as exc:
        workbook_error = (
            "openpyxl is not installed. CSV inventories were created, "
            "but the combined Excel workbook was skipped. "
            "Install it with: python -m pip install openpyxl"
        )
        (destination / "EXCEL_WORKBOOK_SKIPPED.txt").write_text(
            workbook_error + f"\n\nOriginal error: {exc}\n",
            encoding="utf-8",
        )

    except Exception as exc:
        workbook_error = f"{type(exc).__name__}: {exc}"
        (destination / "EXCEL_WORKBOOK_ERROR.txt").write_text(
            traceback.format_exc(),
            encoding="utf-8",
        )

    return {
        "inventory_rows": len(inventory),
        "workbook": str(workbook_path) if workbook_created else None,
        "workbook_created": workbook_created,
        "workbook_error": workbook_error,
        "inventory_csv": str(destination / "all_results_inventory.csv"),
    }


